function render(path = window.location.pathname, hash = window.location.hash) {
  const route = routes[path] || routes['/']
  const currentPath = routes[path] ? path : '/'

  document.title = route.title
  main.innerHTML = `${route.render()}${footerMarkup()}`
  document.dispatchEvent(new CustomEvent('route:change', { detail: { path: currentPath } }))

  if (hash) {
    requestAnimationFrame(() => {
      document.querySelector(hash)?.scrollIntoView({ block: 'start' })
    })
  } else {
    window.scrollTo({ top: 0 })
  }
}

function navigate(path, hash = '') {
  const target = `${path}${hash}`
  if (target !== `${window.location.pathname}${window.location.hash}`) {
    history.pushState({}, '', target)
  }
  render(path, hash)
}

document.addEventListener('click', (event) => {
  const link = event.target.closest('a[data-route]')
  if (!link) return

  const url = new URL(link.href)
  if (url.origin !== window.location.origin) return

  event.preventDefault()
  navigate(url.pathname, url.hash)
})

window.addEventListener('popstate', () => render())

render()
