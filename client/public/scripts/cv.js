function escapeHtml(value) {
  return String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;')
}

function routeLink(path, label, className = '') {
  return `<a class="${className}" href="${path}" data-route>${escapeHtml(label)}</a>`
}

function sectionHeader(kicker, title, text = '') {
  return `
    <div class="section-heading">
      <p class="kicker">${escapeHtml(kicker)}</p>
      <h2>${escapeHtml(title)}</h2>
      ${text ? `<p>${escapeHtml(text)}</p>` : ''}
    </div>
  `
}

function cardList(items, modifier = '') {
  return `
    <div class="card-grid ${modifier}">
      ${items
        .map(
          (item) => `
            <article class="info-card">
              <h3>${escapeHtml(item.title)}</h3>
              ${item.meta ? `<p class="meta">${escapeHtml(item.meta)}</p>` : ''}
              <p>${escapeHtml(item.text)}</p>
            </article>
          `,
        )
        .join('')}
    </div>
  `
}

function simpleList(items, className = 'detail-list') {
  return `
    <ul class="${className}">
      ${items.map((item) => `<li>${escapeHtml(item)}</li>`).join('')}
    </ul>
  `
}

